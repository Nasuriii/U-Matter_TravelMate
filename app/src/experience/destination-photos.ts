// Real destination images with source and reuse credits. Never substitute an
// unrelated destination or an illustrative image for a specific business.
export function destinationPhoto(name: string, province: string): DestinationPhoto | undefined {
  if (name.toLowerCase() === 'agoo' && /la union/i.test(province)) return {
    src: 'https://upload.wikimedia.org/wikipedia/commons/thumb/c/ca/Agoo_Basilica_sanctuary.jpg/960px-Agoo_Basilica_sanctuary.jpg',
    alt: 'Interior of the Basilica of Our Lady of Charity in Agoo', caption: 'Agoo Basilica', author: 'Judgefloro',
    source: 'https://commons.wikimedia.org/wiki/File:Agoo_Basilica_sanctuary.jpg', license: 'Public domain',
  };
  if (name.toLowerCase() === 'san juan' && /la union/i.test(province)) return {
    src: 'https://upload.wikimedia.org/wikipedia/commons/thumb/e/e1/San_Juan_Beach%2C_La_Union%2C_Jan_2024_%282%29.jpg/1280px-San_Juan_Beach%2C_La_Union%2C_Jan_2024_%282%29.jpg',
    alt: 'Waves and sandy shoreline at San Juan Beach, La Union', caption: 'San Juan Beach', author: 'Ralff Nestor Nacor',
    source: 'https://commons.wikimedia.org/wiki/File:San_Juan_Beach,_La_Union,_Jan_2024_(2).jpg', license: 'CC BY-SA 4.0', licenseUrl: 'https://creativecommons.org/licenses/by-sa/4.0/',
  };
  if (name.toLowerCase() === 'baguio' && /benguet/i.test(province)) return {
    src: 'https://upload.wikimedia.org/wikipedia/commons/c/cc/The_Mansion_in_Baguio_City.jpg',
    alt: 'The Mansion building and grounds in Baguio', caption: 'The Mansion, Baguio', author: 'Anna Mae B. Angana',
    source: 'https://commons.wikimedia.org/wiki/File:The_Mansion_in_Baguio_City.jpg', license: 'CC BY-SA 3.0', licenseUrl: 'https://creativecommons.org/licenses/by-sa/3.0/',
  };
  const key = name.trim().toLowerCase() === 'san fernando' ? 'san fernando city' : name.trim().toLowerCase();
  return /la union/i.test(province) ? additionalDestinationPhotos[key] : undefined;
}
